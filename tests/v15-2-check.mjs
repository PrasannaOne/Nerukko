import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
const worker = await readFile(new URL('../src/worker.js', import.meta.url), 'utf8');
const page = await readFile(new URL('../public/index.html', import.meta.url), 'utf8');
const sw = await readFile(new URL('../public/service-worker.js', import.meta.url), 'utf8');
assert.match(worker, /data\.type === "private-signal"/);
assert.match(worker, /delivery:\$\{key\}/);
assert.match(worker, /getIceConfiguration\(request, env, url\.searchParams\.get\("provider"\)/);
assert.match(worker, /provider === "turnix" \? await turnix\(\) : await metered\(\)/);
assert.match(worker, /const servers = await turnix\(\)/);
assert.match(worker, /const servers = await metered\(\)/);
assert.match(page, /iceTransportPolicy:'relay'/);
assert.match(page, /\['turnix','metered'\]/);
assert.match(page, /connectPrivatePeer\(friend\)/);
assert.match(page, /private-text/);
assert.match(page, /private-signal/);
assert.match(page, /async function fallbackGroupPeer/);
assert.match(page, /connectionState === 'disconnected'/);
assert.match(page, /getProviderIceServers\('metered'\)/);
assert.match(page, /providerIceCache = new Map/);
assert.match(page, /provider==='turnix'.*entry\.fallbackStarted/);
assert.match(sw, /neruko-shell/);
console.log('Neruko shared TURN fallback and private WebRTC checks passed.');
